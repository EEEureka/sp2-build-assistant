"""Build SDK-owned skill/knowledge resources; no global installation changes."""
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'sdk/sp2model/resources/skill'


def main():
    # Curated, version-bound resources only; raw audit/source/player files never
    # become part of the SDK or skill through this stage.
    from stage_knowledge_077 import main as stage_knowledge
    stage_knowledge()
    # Preserve the legacy knowledge.complex response shape without distributing
    # its historical decompiler statement excerpts. FT example expressions in
    # the new index are user-facing language examples and are not affected.
    legacy = json.loads((ROOT / 'knowledge/complex-parts.json').read_text(encoding='utf-8-sig'))
    stripped = 0
    for family in legacy.get('families', []):
        for source in family.get('sourceFiles', []):
            for parameter in source.get('parameters', []):
                if 'expression' in parameter:
                    parameter['expression'] = None
                    parameter['expressionStatus'] = 'source-reference-only'
                    stripped += 1
    legacy['distribution'] = {'sourceStatementsRemoved': stripped,
        'reason': 'Legacy shape retained; use knowledge.get for derived semantics and source references.'}
    (ROOT / 'sdk/sp2model/resources/knowledge/complex-parts.json').write_text(
        json.dumps(legacy, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    # The old 0.5 audit mixed private template identifiers into every property
    # row. No runtime API consumes it. Retain a truthful resource pointer, not
    # a partially redacted snapshot whose counts could imply full coverage.
    old_coverage = json.loads((ROOT / 'knowledge/editable-coverage.json').read_text(encoding='utf-8-sig'))
    coverage_pointer = {'available': False, 'status': 'historical_snapshot_not_distributed',
        'gameVersion': old_coverage.get('gameVersion'), 'registryVersion': old_coverage.get('registryVersion'),
        'types': {}, 'fullyCertifiedTypePropertyPairs': 0,
        'reason': 'Historical discovery included private template references. The full audit stays in the source workspace.',
        'currentKnowledge': 'knowledge.status', 'currentFields': 'knowledge.export collection=fields',
        'liveWriteAuthority': 'properties.describe on the explicitly selected instance'}
    (ROOT / 'sdk/sp2model/resources/knowledge/editable-coverage.json').write_text(
        json.dumps(coverage_pointer, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    shutil.copytree(ROOT / 'skills/sp2-build-assistant', TARGET, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    entry = (ROOT / 'deployment/skills/sp2-build-assistant/SKILL.md').read_text(encoding='utf-8')
    entry = entry.replace('../../../sdk/examples/', 'examples/').replace('../../../sdk/', 'references/').replace('../../../skills/sp2-build-assistant/', '')
    (TARGET / 'SKILL.md').write_text(entry, encoding='utf-8')
    for name in ('API.md', 'Modeling-Workflow.md', 'Modeling-Semantic-Workflow.md', 'Modeling-Reference-Features.md', 'Advanced-Native.md', 'Services.md', 'Hard-Surfaces.md', 'Knowledge.md', 'Knowledge-Funky.md', 'Updates.md'):
        text = (ROOT / 'sdk' / name).read_text(encoding='utf-8-sig').replace('(examples/', '(../examples/').replace('(README.md)', '(../SKILL.md)')
        (TARGET / 'references' / name).write_text(text, encoding='utf-8')
    shutil.copytree(ROOT / 'sdk/examples', TARGET / 'examples', dirs_exist_ok=True, ignore=shutil.ignore_patterns('__pycache__'))
    for cache in TARGET.rglob('*.pyc'):
        if cache.is_symlink() or not cache.resolve().is_relative_to(TARGET.resolve()): raise ValueError('Unexpected redirected resource cache')
        cache.unlink()  # generated bytecode only; never user data or test runtimes
    for path in TARGET.rglob('*.md'):
        text = path.read_text(encoding='utf-8-sig').replace('sp2build ', 'sp2model ').replace('`sp2build`', '`sp2model`').replace('sp2build.cmd', 'sp2model.cmd')
        text = text.replace('data.identity', 'result.identity').replace('designer.status.data.', 'designer.status.result.')
        path.write_text(text, encoding='utf-8')
    # The old long entry is retained as a historical semantics reference, not a
    # second current workflow with obsolete write instructions.
    (TARGET / 'operating-contracts.md').write_text('# Current operating contracts\n\nUse [Services](references/Services.md), [API](references/API.md) and the C01-C08 rules in [SKILL](SKILL.md). Native semantics are covered in the conditional references. CLI envelopes use ok/result; native batch writes require explicit scope and a reviewed preview.\n', encoding='utf-8')
    sys.path.insert(0, str(ROOT / 'sdk'))
    from sp2model._services import build_guidance as guide
    guide.ROOT = TARGET
    migration_path = TARGET / 'references/rule-migration.json'
    migration = json.loads(migration_path.read_text(encoding='utf-8-sig'))
    old = {name: row['sha256'] for name, row in migration['topics'].items()}
    for name, row in migration['topics'].items():
        row.update(sha256=guide._hash(guide._read(name)), pageCount=len(guide._pages(guide._read(name))))
    migration['corePolicyUpdate'] = {'version': '0.7.8a1-development', 'previousTopicHashes': old,
        'reason': 'Short semantic operations, original-intent recovery and verified delivery; native boundaries and context retention limits preserved.'}
    migration_path.write_text(json.dumps(migration, ensure_ascii=False, indent=2), encoding='utf-8')
    for document in [TARGET / 'SKILL.md']:
        for link in re.findall(r'\]\(([^)]+)\)', document.read_text(encoding='utf-8')):
            if '://' not in link and not link.startswith('#'): assert (document.parent / link.split('#')[0]).is_file(), link
    assert len(entry) < 8192
    assert len(json.dumps(guide.prepare(), ensure_ascii=False, indent=2)) < 4096
    print(json.dumps({'status': 'passed', 'entryCharacters': len(entry), 'coreSha256': guide._hash(guide._read('core')),
                      'resources': len(list(TARGET.rglob('*.*')))}))


if __name__ == '__main__': main()
