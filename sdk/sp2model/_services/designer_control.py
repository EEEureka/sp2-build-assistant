"""Contracts for native navigation, selection and craft storage."""

ACTIONS = ['enter', 'load', 'select', 'save', 'new', 'delete', 'menu', 'quit']
def input_schema():
    return {'type':'object','additionalProperties':False,
        'properties':{'action':{'enum':ACTIONS},
            'expectedScene':{'enum':['MainMenu','Designer','Terrain']},'requestId':{'type':'string','minLength':1},
            'craftSessionId':{'type':'string'},'expectedRevision':{'type':'integer','minimum':0},
            'expectedCraftName':{'type':'string'},'discardCurrent':{'type':'boolean'},
            'craftId':{'type':'string','minLength':1},'partId':{'type':'integer','minimum':0},'clear':{'type':'boolean'},
            'expectedSavedName':{'type':'string','minLength':1},'expectedSavedModifiedUtc':{'type':'string','minLength':1},
            'name':{'type':'string','minLength':1,'maxLength':200,
                    'description':'Save name without .xml, optionally with relative folders. Root is the native craft directory, independent of the current folder. Traversal, reserved names and native protected directories are rejected.'},
            'overwrite':{'type':'boolean','default':False,
                         'description':'Explicitly replace an existing target; otherwise craft_exists is returned before saving.'}},
        'required':['action','expectedScene','requestId'],
        'allOf':[
            {'if':{'properties':{'expectedScene':{'enum':['Designer','Terrain']}}},
             'then':{'required':['craftSessionId','expectedRevision','expectedCraftName']}},
            {'if':{'properties':{'action':{'enum':['new','load','menu','quit']},'expectedScene':{'enum':['Designer','Terrain']}}},
             'then':{'required':['discardCurrent'],'properties':{'discardCurrent':{'const':True}}}},
            {'if':{'properties':{'action':{'enum':['load','delete']}}},'then':{'required':['craftId']},'else':{'not':{'required':['craftId']}}},
            {'if':{'properties':{'action':{'const':'delete'}}},'then':{'required':['expectedSavedName','expectedSavedModifiedUtc']},'else':{'not':{'anyOf':[{'required':['expectedSavedName']},{'required':['expectedSavedModifiedUtc']}]}}},
            {'if':{'properties':{'action':{'const':'save'}}},
             'then':{'required':['name'],'not':{'required':['discardCurrent']}},
             'else':{'not':{'anyOf':[{'required':['name']},{'required':['overwrite']}]}}},
            {'if':{'properties':{'action':{'const':'select'}}},
             'then':{'oneOf':[{'required':['partId'],'not':{'required':['clear']}},
                              {'required':['clear'],'properties':{'clear':{'const':True}},'not':{'required':['partId']}}]},
             'else':{'not':{'anyOf':[{'required':['clear']},{'required':['partId']}]}}},
            {'if':{'properties':{'action':{'enum':['load','select','save','new','menu']}}},'then':{'properties':{'expectedScene':{'enum':['Designer','Terrain']}}}},
            {'if':{'properties':{'action':{'const':'enter'}}},'then':{'properties':{'expectedScene':{'const':'MainMenu'}}}}],
        'description':'Native game APIs. save persists the named craft and can recenter it; use the returned identity. new replaces the editor with the native blank template and its starter control part, but does not persist a named save. Session checkpoints do not survive replacement.'}

def output_data_schema():
    return {'type':'object','required':['action','scene','desktopInputUsed'],
        'properties':{'action':{'enum':ACTIONS},'scene':{'type':'string'},
            'desktopInputUsed':{'const':False},'identity':{'anyOf':[{'$ref':'#/$defs/Identity'},{'type':'null'}]},
            'craftName':{'type':['string','null']},'selectedPartId':{'type':['integer','null']},
            'sessionChanged':{'type':'boolean'},'saved':{'type':'boolean'},'partCount':{'type':['integer','null']},
            'persistedCraft':{'type':'object','additionalProperties':False,
                'required':['craftId','name','overwritten','lastModifiedUtc','persistenceVerified','verification'],
                'properties':{'craftId':{'type':'string'},'name':{'type':'string'},'overwritten':{'type':'boolean'},
                    'lastModifiedUtc':{'type':'string'},'persistenceVerified':{'const':True},
                    'verification':{'const':'native_database_save_return'}}},
            'deletedCraft':{'type':'object','additionalProperties':False,
                'required':['craftId','name','deletionVerified'],
                'properties':{'craftId':{'type':'string'},'name':{'type':'string'},
                              'deletionVerified':{'const':True}}},
            'shutdownScheduled':{'type':'boolean'},'meaning':{'type':['string','null']}},
        'allOf':[{'if':{'properties':{'action':{'const':'save'}}},
                  'then':{'required':['saved','persistedCraft','identity','sessionChanged'],
                          'properties':{'saved':{'const':True},'sessionChanged':{'const':False}}},
                  'else':{'properties':{'saved':{'const':False}},'not':{'required':['persistedCraft']}}},
                 {'if':{'properties':{'action':{'const':'delete'}}},
                  'then':{'required':['deletedCraft','identity','sessionChanged'],
                          'properties':{'sessionChanged':{'const':False}}},
                  'else':{'not':{'required':['deletedCraft']}}}]}
